"""Схема: обратноходовый преобразователь 20 Вт, 220 В AC → 15 В / 1,33 А на UC3843."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from schgen import Schematic  # noqa: E402

s = Schematic("Flyback 20 W: 220 VAC -> 15 V / 1.33 A (UC3843)", "flyback20w")
R, C, CP = "Device:R", "Device:C", "Device:C_Polarized"

# ---------- Вход ----------
s.add("J1", "Connector_Generic:Conn_01x02", "AC 220V", 25.4, 63.5, 180, ref_pos=(22.86, 57.15), val_pos=(17.78, 69.85))
s.add("F1", "Device:Fuse", "T1A 250V", 45.72, 60.96, 90)
s.add("RV1", "Device:Varistor", "S07K275", 55.88, 68.58)
s.add("CX1", C, "100n X2", 66.04, 68.58)
s.add("TH1", "Device:Thermistor_NTC", "NTC 5R", 78.74, 60.96, 90, val_pos=(78.74, 56.9), ref_pos=(78.74, 54.2))
s.add("BR1", "Device:D_Bridge_+-AA", "MB6S", 101.6, 68.58, ref_pos=(104.14, 62.23), val_pos=(104.14, 76.2))
s.add("C1", CP, "47u 400V", 121.92, 72.39)

# ---------- Силовая часть ----------
s.add("T1", "Device:Transformer_1P_2S", "Lp 1.2mH, 83:14:12, EE25", 177.8, 72.39,
      ref_pos=(175.26, 59.69), val_pos=(166.37, 90.17))
s.add("R2", R, "22k 2W", 139.7, 72.39)
s.add("C2", C, "2.2n 1kV", 149.86, 72.39)
s.add("D1", "Device:D", "UF4007", 144.78, 88.9, 270)
s.add("Q1", "Device:Q_NMOS", "650V N-MOSFET", 167.64, 120.65, ref_pos=(173.99, 118.11), val_pos=(173.99, 120.65))
s.add("R4", R, "22R", 146.05, 120.65, 90)
s.add("R5", R, "10k", 157.48, 129.54)
s.add("R6", R, "1R 0.5W", 170.18, 133.35)
s.add("R7", R, "1k", 185.42, 125.73, 90)
s.add("C5", C, "470p", 195.58, 129.54)
s.add("CY1", C, "2.2n Y1", 203.2, 147.32)

# ---------- ШИМ-контроллер ----------
s.add("U1", "Regulator_Controller:UC3843_DIP8", "UC3843", 114.3, 125.73, ref_pos=(121.92, 138.43), val_pos=(121.92, 140.97))
s.add("R1", R, "200k 1206", 66.04, 91.44, 90)
s.add("R3", R, "200k 1206", 78.74, 91.44, 90)
s.add("C3", CP, "47u 25V", 86.36, 104.14)
s.add("C4", C, "100n", 99.06, 104.14)
s.add("C6", C, "100n", 76.2, 137.16)
s.add("R8", R, "12k", 86.36, 137.16)
s.add("C7", C, "2.2n", 86.36, 147.32)

# ---------- Выход ----------
s.add("D2", "Device:D", "UF4004", 196.85, 74.93, 180, ref_pos=(196.85, 72.39), val_pos=(196.85, 78.74))
s.add("D3", "Device:D_Schottky", "MBR10150", 199.39, 62.23, 180)
s.add("C9", CP, "1000u 25V", 218.44, 72.39)
s.add("C10", CP, "1000u 25V", 231.14, 72.39)
s.add("L1", "Device:L", "2.2u", 243.84, 62.23, 90)
s.add("C11", CP, "220u 25V", 256.54, 72.39)
s.add("J2", "Connector_Generic:Conn_01x02", "15V 1.33A", 281.94, 62.23, ref_pos=(279.4, 57.15), val_pos=(279.4, 69.85))

# ---------- Обратная связь ----------
s.add("U2", "Isolator:PC817", "PC817", 222.25, 138.43, 180, ref_pos=(214.63, 130.81), val_pos=(222.25, 130.81))
s.add("R9", R, "1k", 248.92, 116.84)
s.add("R10", R, "1k", 238.76, 138.43)
s.add("U3", "Reference_Voltage:TL431DBV", "TL431", 264.16, 152.4, 90, ref_pos=(267.97, 156.21), val_pos=(267.97, 158.75))
s.add("R11", R, "11k", 254.0, 144.78)
s.add("R13", R, "2.2k", 254.0, 160.02)
s.add("R12", R, "4.7k", 238.76, 152.4, 90)
s.add("C12", C, "47n", 247.65, 152.4, 90)

# ---------- Цепи ----------
s.net("AC_L", "J1.2", "F1.1")
s.net("AC_LF", "F1.2", "RV1.1", "CX1.1", "TH1.1")
s.net("AC_L2", "TH1.2", "BR1.3")
s.net("AC_N", "J1.1", "RV1.2", "CX1.2", "BR1.4")
s.net("VBULK", "BR1.1", "C1.1", "T1.1", "R2.1", "C2.1", "R1.1")
s.net("CLAMP", "R2.2", "C2.2", "D1.1")
s.net("DRAIN", "T1.2", "D1.2", "Q1.D")
s.net("START", "R1.2", "R3.1")
s.net("VCC", "R3.2", "C3.1", "C4.1", "U1.7", "D2.1")
s.net("AUX", "T1.5", "D2.2")
s.net("DRV", "U1.6", "R4.1")
s.net("GATE", "R4.2", "Q1.G", "R5.1")
s.net("SRC", "Q1.S", "R6.1", "R7.1")
s.net("CS", "R7.2", "C5.1", "U1.3")
s.net("VREF", "U1.8", "R8.1", "C6.1")
s.net("RC", "U1.4", "R8.2", "C7.1")
s.net("COMP", "U1.1", "U2.4")
s.net("GNDPWR", "BR1.2", "C1.2", "T1.6", "R5.2", "R6.2", "C5.2", "U1.5", "U1.2",
      "C3.2", "C4.2", "C7.2", "C6.2", "U2.3", "CY1.1")
s.net("SEC", "T1.3", "D3.2")
s.net("VRAW", "D3.1", "C9.1", "C10.1", "L1.1")
s.net("+15V", "L1.2", "C11.1", "J2.1", "R9.1", "R11.1")
s.net("GND", "T1.4", "C9.2", "C10.2", "C11.2", "J2.2", "U3.5", "R13.2", "CY1.2")
s.net("LED_A", "R9.2", "U2.1", "R10.2")
s.net("LED_K", "U2.2", "R10.1", "U3.3", "R12.1")
s.net("COMP_RC", "R12.2", "C12.1")
s.net("FB", "U3.4", "C12.2", "R11.2", "R13.1")

# ---------- Провода и шины ----------
s.wire("J1.2", "F1.1")
s.rail("F1.2", "RV1.1", "CX1.1", "TH1.1", y=60.96)
s.wire("TH1.2", "BR1.3")
s.rail("J1.1", "RV1.2", "CX1.2", "BR1.4", y=80.01)
s.rail("BR1.1", "C1.1", "R2.1", "C2.1", "T1.1", y=55.88)
s.rail("R2.2", "C2.2", "D1.1", y=80.01)
s.rail("D1.2", "T1.2", "Q1.D", y=96.52)
s.wire("R1.2", "R3.1")
s.rail("R3.2", "C3.1", "C4.1", "U1.7", y=99.06)
s.wire("U1.6", "R4.1")
s.rail("R4.2", "R5.1", "Q1.G", y=120.65)
s.rail("Q1.S", "R6.1", "R7.1", y=125.73)
s.rail("R7.2", "C5.1", y=125.73)
s.rail("C6.1", "R8.1", y=133.35)
s.wire("R8.2", "C7.1")
s.wire("T1.5", "D2.2")
s.wire("T1.3", "D3.2")
s.rail("D3.1", "C9.1", "C10.1", "L1.1", y=62.23)
s.rail("U2.2", "R10.1", y=135.89)
s.rail("U2.1", "R10.2", "R9.2", y=140.97)
s.wire("R12.2", "C12.1")
s.rail("C12.2", "R11.2", "R13.1", "U3.4", y=152.4)
s.rotate_power.update({"U1.2", "T1.4", "T1.6", "U2.3"})
s.label_on("R8.2", 86.36, 142.24, 0)

# ---------- Флаги питания для ERC ----------
s.flag("VCC", 60.96, 101.6)
s.flag("GNDPWR", 132.08, 152.4)
s.flag("GND", 213.36, 162.56)
s.flag("+15V", 289.56, 50.8)

# ---------- Подписи ----------
s.text("ВХОД 220 В AC", 20.32, 48.26, 2.2, True)
s.text("СИЛОВАЯ ЧАСТЬ", 134.62, 48.26, 2.2, True)
s.text("ВЫХОД 15 В / 1,33 А", 210.82, 48.26, 2.2, True)
s.text("ШИМ UC3843, 65 кГц", 91.44, 93.98, 2.2, True)
s.text("ОБРАТНАЯ СВЯЗЬ", 210.82, 109.22, 2.2, True)
s.text("T1: Lp = 1,2 мГн; Np:Ns:Naux = 83:14:12; EE25 с зазором; • — начало обмотки", 134.62, 172.72, 1.6)
s.text("Обмотка 5–6 — вспомогательная (питание UC3843), она на первичной стороне", 134.62, 176.53, 1.6)
s.text("Первичная земля GNDPWR и вторичная GND связаны только через CY1 (Y1)", 134.62, 180.34, 1.6)

# точки начала обмоток: первичка — у VBULK (выв. 1), вторички — у земли (выв. 4 и 6)
for num, dx, dy in (("1", 5.08, -1.27), ("4", -5.08, 1.27), ("6", -5.08, 1.27)):
    x, y = s.parts["T1"].pin_tip(num)
    s.dot(x + dx, y + dy)

out = Path(__file__).with_name("flyback20w.kicad_sch")
out.write_text(s.build(), encoding="utf-8")
print("OK", out)
